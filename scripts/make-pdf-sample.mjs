#!/usr/bin/env node
/**
 * 生成一个**结构合规**的最小 PDF 样本（xref 表偏移正确）。
 *
 * 存在的意义：spike/samples/sample.pdf 只有一页、文本极短，用它验证 PDF 通道说服力不足。
 * 本脚本产出一份多段英文、结构合规（xref 偏移正确、内容流不压缩）的 PDF 用于回归验证。
 * 注：sample.pdf 原先报 bad XRef entry 的真实原因是 pdf-parse 忽略 Buffer.byteOffset
 * （详见 packages/server/src/parser/pdf.ts 顶部注释），不是样本损坏，现已修复。
 *
 * 用法：node scripts/make-pdf-sample.mjs [输出路径]
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = process.argv[2] ? path.resolve(process.argv[2]) : path.join(ROOT, 'spike', 'samples', 'gen-sample.pdf');

/** PDF 文本串转义：反斜杠与圆括号 */
function escapePdfText(input) {
  return String(input)
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .replace(/[^\x20-\x7e]/g, '?');
}

/**
 * 组装 PDF：5 个间接对象 + 正确 xref + trailer。
 * 全部按 latin1 单字节写入，保证 offset 计算与字节数一致。
 */
export function buildPdf(lines) {
  const body = ['BT', '/F1 14 Tf', '72 720 Td', '20 TL', ...lines.map((l) => `(${escapePdfText(l)}) Tj T*`), 'ET'].join('\n');
  const streamBytes = Buffer.byteLength(body, 'latin1');

  const objects = [
    null,
    '<</Type /Catalog /Pages 2 0 R>>',
    '<</Type /Pages /Kids [3 0 R] /Count 1>>',
    // 实测：Resources 里必须带 /ProcSet [/PDF /Text]，否则 pdf.js 的 getTextContent
    // 会抛 "GetTextContent: page 0" 并返回空文本（页数正常但 text === ''）
    '<</Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R ' +
      '/Resources <</ProcSet [/PDF /Text] /Font <</F1 5 0 R>>>>>>',
    `<</Length ${streamBytes}>>\nstream\n${body}\nendstream`,
    '<</Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding>>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (let i = 1; i < objects.length; i += 1) {
    offsets[i] = Buffer.byteLength(pdf, 'latin1');
    pdf += `${i} 0 obj\n${objects[i]}\nendobj\n`;
  }

  const xrefOffset = Buffer.byteLength(pdf, 'latin1');
  pdf += 'xref\n0 6\n';
  pdf += '0000000000 65535 f \n';
  for (let i = 1; i < objects.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<</Size 6 /Root 1 0 R>>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdf, 'latin1');
}

const SAMPLE_LINES = [
  'KB Parser Regression Sample',
  'Generated by scripts/make-pdf-sample.mjs',
  'This PDF has a valid xref table and an uncompressed content stream.',
  'pdf-parse should extract all of these lines as plain text.',
];

const buffer = buildPdf(SAMPLE_LINES);
mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, buffer);
console.log(`已生成合规 PDF 样本：${OUT}（${buffer.byteLength} 字节）`);
