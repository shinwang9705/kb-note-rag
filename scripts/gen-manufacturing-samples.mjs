// ================= 生成文件 =================
mkdirSync(OUT_DIR, { recursive: true });

const list = DOCS.map((doc, i) => {
  const no = String(i + 1).padStart(3, '0');
  const filename = `${no}-${doc.title}.md`;
  const full = `# ${doc.title}\n\n> 分类：${doc.category}\n\n${doc.body}\n`;
  writeFileSync(path.join(OUT_DIR, filename), full, 'utf8');
  return { no, title: doc.title, category: doc.category, filename };
});

// 文档清单
const byCategory = new Map();
for (const item of list) {
  const arr = byCategory.get(item.category) ?? [];
  arr.push(item);
  byCategory.set(item.category, arr);
}

let md = `# 智能制造测试资料清单\n\n共 ${list.length} 份文档，用于测试知识库上传、分块、检索、问答与重排序。\n\n`;
md += `存放目录：\`samples/smart-manufacturing/\`\n\n## 分类统计\n\n| 分类 | 数量 |\n|---|---|\n`;
for (const [cat, arr] of byCategory) {
  md += `| ${cat} | ${arr.length} |\n`;
}
md += `\n## 文档明细\n\n| 序号 | 分类 | 标题 | 文件名 |\n|---|---|---|---|\n`;
for (const item of list) {
  md += `| ${item.no} | ${item.category} | ${item.title} | ${item.filename} |\n`;
}

writeFileSync(path.join(ROOT, 'samples', 'manufacturing-doc-list.md'), md, 'utf8');
console.log(`已生成 ${list.length} 份文档 -> ${OUT_DIR}`);
console.log(`文档清单 -> ${path.join(ROOT, 'samples', 'manufacturing-doc-list.md')}`);
